import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import {
  flatten,
  merge,
  resolve,
  cssName,
  cssValue,
  contrast,
} from "./token-engine.mjs";
const themes = JSON.parse(readFileSync("tokens/themes.json", "utf8"));
const modes = {},
  trees = {},
  reports = [];
for (const [mode, files] of Object.entries(themes)) {
  let tree = {};
  for (const file of files)
    tree = merge(tree, JSON.parse(readFileSync(`tokens/${file}`, "utf8")));
  trees[mode] = tree;
  const raw = flatten(tree);
  modes[mode] = Object.fromEntries(
    Object.entries(raw).map(([name, t]) => [
      name,
      {
        name,
        type: t.$type,
        reference: typeof t.$value === "string" ? t.$value : null,
        value: cssValue(t.$type, resolve(raw, name)),
        resolved: resolve(raw, name),
        layer: name.split(".")[0],
      },
    ]),
  );
  for (const [fg, bg, min] of [
    ["text", "canvas", 4.5],
    ["text-secondary", "surface", 4.5],
    ["text-tertiary", "canvas", 4.5],
    ["accent", "canvas", 4.5],
    ["on-accent", "accent", 4.5],
    ["danger", "danger-subtle", 4.5],
    ["warning", "warning-subtle", 4.5],
    ["info", "info-subtle", 4.5],
    ["border-control", "surface", 3],
    ["focus", "surface", 3],
  ]) {
    const ratio = contrast(
      modes[mode][`semantic.color.${fg}`].value,
      modes[mode][`semantic.color.${bg}`].value,
    );
    reports.push({ mode, fg, bg, ratio: +ratio.toFixed(2), minimum: min });
    if (ratio < min)
      throw Error(`Contrast fails: ${mode} ${fg}/${bg} ${ratio}`);
  }
}
if (
  JSON.stringify(Object.keys(modes.light)) !==
  JSON.stringify(Object.keys(modes.dark))
)
  throw Error("Theme coverage mismatch");
const serialize = (mode) =>
  Object.values(modes[mode])
    .map(
      (t) =>
        `  ${cssName(t.name)}: ${t.reference ? `var(${cssName(t.reference.slice(1, -1))})` : t.type === "dimension" && t.name.includes(".size.") ? `${t.resolved.value / 16}rem` : t.value};`,
    )
    .join("\n");
const css = `/* Generated by npm run tokens:build. */\n:root, [data-theme="light"] {\n${serialize("light")}\n}\n.dark, [data-theme="dark"] {\n${serialize("dark")}\n}\n`;
mkdirSync("src/generated", { recursive: true });
mkdirSync("public/generated", { recursive: true });
writeFileSync("src/generated/tokens.css", css);
writeFileSync("public/generated/rosemary.css", css);
writeFileSync(
  "src/generated/tokens.ts",
  `// Generated. Source: tokens/*.tokens.json\nexport const tokenModes = ${JSON.stringify(modes, null, 2)} as const;\nexport type TokenName = keyof typeof tokenModes.light;\nexport const tokenNames = Object.keys(tokenModes.light) as TokenName[];\n`,
);
writeFileSync(
  "public/generated/rosemary.tokens.json",
  JSON.stringify(trees, null, 2) + "\n",
);
for (const mode of ["light", "dark"])
  writeFileSync(
    `public/generated/${mode}.tokens.json`,
    JSON.stringify(trees[mode], null, 2) + "\n",
  );
// Each native output exposes the same semantic names and typed values for both modes.
const entries = (mode) =>
  Object.values(modes[mode]).filter((t) => t.layer !== "primitive");
const id = (t) => t.name.replaceAll(".", "_").replaceAll("-", "_");
const argb = (t) => "0xFF" + t.value.slice(1).toUpperCase();
const dart = (t) =>
  t.type === "color"
    ? `Color(${argb(t)})`
    : t.type === "dimension"
      ? `${t.resolved.value.toFixed(1)}`
      : t.type === "duration"
        ? `Duration(milliseconds: ${t.resolved.value})`
        : t.type === "cubicBezier"
          ? `Cubic(${t.resolved.join(", ")})`
          : `<String>[${t.resolved.map((s) => JSON.stringify(s)).join(", ")}]`;
writeFileSync(
  "public/generated/rosemary_tokens.dart",
  `// Generated; Flutter SDK needed.\nimport 'package:flutter/material.dart';\n${[
    "light",
    "dark",
  ]
    .map(
      (mode) =>
        `class Rosemary${mode === "light" ? "Light" : "Dark"}Tokens {\n${entries(
          mode,
        )
          .map((t) => `  static const ${id(t)} = ${dart(t)};`)
          .join("\n")}\n}`,
    )
    .join("\n")}\n`,
);
mkdirSync("platforms/flutter/lib", { recursive: true });
writeFileSync(
  "platforms/flutter/lib/rosemary_tokens.dart",
  readFileSync("public/generated/rosemary_tokens.dart"),
);
const swift = (t) =>
  t.type === "color"
    ? `Color(.sRGB, red: ${t.resolved.components[0]}, green: ${t.resolved.components[1]}, blue: ${t.resolved.components[2]}, opacity: ${t.resolved.alpha})`
    : t.type === "dimension"
      ? `CGFloat(${t.resolved.value})`
      : t.type === "duration"
        ? `Double(${t.resolved.value}/1000.0)`
        : t.type === "cubicBezier"
          ? `[Double](${JSON.stringify(t.resolved)})`
          : `[String](${JSON.stringify(t.resolved)})`;
writeFileSync(
  "public/generated/RosemaryTokens.swift",
  `import SwiftUI\n${["light", "dark"]
    .map(
      (mode) =>
        `public enum Rosemary${mode === "light" ? "Light" : "Dark"}Tokens {\n${entries(
          mode,
        )
          .map((t) => `  public static let ${id(t)} = ${swift(t)}`)
          .join("\n")}\n}`,
    )
    .join("\n")}\n`,
);
const kotlin = (t) =>
  t.type === "color"
    ? `Color(${argb(t)})`
    : t.type === "dimension"
      ? `${t.resolved.value}.${t.name.includes(".size.") ? "sp" : "dp"}`
      : t.type === "duration"
        ? `${t.resolved.value}`
        : t.type === "cubicBezier"
          ? `CubicBezierEasing(${t.resolved.map((n) => `${n.toFixed(2)}f`).join(", ")})`
          : `listOf(${t.resolved.map((s) => JSON.stringify(s)).join(", ")})`;
writeFileSync(
  "public/generated/RosemaryTokens.kt",
  `package design.rosemary.tokens\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\nimport androidx.compose.animation.core.CubicBezierEasing\n${[
    "light",
    "dark",
  ]
    .map(
      (mode) =>
        `object Rosemary${mode === "light" ? "Light" : "Dark"}Tokens {\n${entries(
          mode,
        )
          .map((t) => `  val ${id(t)} = ${kotlin(t)}`)
          .join("\n")}\n}`,
    )
    .join("\n")}\n`,
);
const csharp = (t) =>
  t.type === "color"
    ? `Color.FromArgb(255, ${t.resolved.components.map((n) => Math.round(n * 255)).join(", ")})`
    : t.type === "dimension"
      ? `${t.resolved.value}.0`
      : t.type === "duration"
        ? `TimeSpan.FromMilliseconds(${t.resolved.value})`
        : t.type === "cubicBezier"
          ? `new double[] { ${t.resolved.join(", ")} }`
          : `new string[] { ${t.resolved.map((s) => JSON.stringify(s)).join(", ")} }`;
writeFileSync(
  "public/generated/RosemaryTokens.cs",
  `using System;\nusing Windows.UI;\nnamespace Rosemary.Design;\n${[
    "light",
    "dark",
  ]
    .map(
      (mode) =>
        `public static class Rosemary${mode === "light" ? "Light" : "Dark"}Tokens {\n${entries(
          mode,
        )
          .map(
            (t) =>
              `  public static readonly ${t.type === "color" ? "Color" : t.type === "duration" ? "TimeSpan" : t.type === "cubicBezier" ? "double[]" : t.type === "fontFamily" ? "string[]" : "double"} ${id(t)} = ${csharp(t)};`,
          )
          .join("\n")}\n}`,
    )
    .join("\n")}\n`,
);
writeFileSync(
  "public/generated/validation.json",
  JSON.stringify(
    {
      tokensPerMode: Object.keys(modes.light).length,
      modes: Object.keys(modes),
      contrast: reports,
      nativeStatus:
        "Generation checks only; native SDK build results are recorded separately in guide/native-checks.json",
    },
    null,
    2,
  ) + "\n",
);
console.log(
  `Tokens: ${Object.keys(modes.light).length} × 2 modes; ${reports.length} contrast pairs passed.`,
);

for (const [source, destination] of [
  [
    "public/generated/RosemaryTokens.swift",
    "platforms/swiftui/Sources/RosemaryUI/RosemaryTokens.swift",
  ],
  [
    "public/generated/RosemaryTokens.kt",
    "platforms/android/rosemary-compose/src/main/java/design/rosemary/tokens/RosemaryTokens.kt",
  ],
]) {
  mkdirSync(destination.slice(0, destination.lastIndexOf("/")), {
    recursive: true,
  });
  writeFileSync(destination, readFileSync(source));
}
