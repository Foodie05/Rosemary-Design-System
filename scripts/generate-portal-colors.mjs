import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const manifest=JSON.parse(fs.readFileSync(new URL('vendor/material-color-utilities.json',root),'utf8'));
for(const [file,key] of [['vendor/material-color-utilities.js','bundleSha256'],['vendor/material-color-utilities-0.4.0.tgz','sourceSha256']])assert.equal(crypto.createHash('sha256').update(fs.readFileSync(new URL(file,root))).digest('hex'),manifest[key]);
assert.equal('sha512-'+crypto.createHash('sha512').update(fs.readFileSync(new URL('vendor/material-color-utilities-0.4.0.tgz',root))).digest('base64'),manifest.integrity);
const context=vm.createContext({window:{}});
for(const file of ['vendor/material-color-utilities.js','color-engine.js'])vm.runInContext(fs.readFileSync(new URL(file,root),'utf8'),context,{filename:file});
const scheme=context.window.RosemaryColors.generate();
const css='/* Generated by scripts/generate-portal-colors.mjs from the Rosemary default recipe. */\n'+Object.entries(scheme.colors).map(([mode,colors])=>`${mode==='light'?':root':'[data-theme=dark]'} {\n${Object.entries(colors).map(([key,value])=>`  --${key}:${value};`).join('\n')}\n}`).join('\n')+'\n';
const target=new URL('color-roles.css',root);
if(check)assert.equal(fs.readFileSync(target,'utf8'),css,'Default role CSS is current');else fs.writeFileSync(target,css);
console.log(`${check?'Checked':'Generated'} default HCT role CSS and pinned Material dependency hashes.`);
